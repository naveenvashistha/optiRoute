from pydantic import BaseModel, Field, UUID4
from typing import Literal, Optional

class Message(BaseModel):
    """A user or assistant message in the submitted conversation."""
    role: Literal["user", "assistant"]
    content: str = Field(..., min_length=1, max_length=20000)

class ChatRequest(BaseModel):
    """Accept a nonempty conversation and a valid temporary session identifier."""
    messages: list[Message] = Field(..., min_length=1)
    session_id: UUID4 = Field(..., description="UUID v4 generated by the React frontend to track the temporary Redis session.")
    edit_index: Optional[int] = Field(default=None, ge=0, strict=True)
